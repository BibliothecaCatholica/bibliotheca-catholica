#!/usr/bin/env python3
"""Offline inventory of actual hosted editions; indicators are review leads, not errors.

Run: python3 tools/audit_hosted_texts.py
Writes the living inventory in docs/HOSTED-TEXT-INVENTORY.md. Never imports a book.
"""
import hashlib
import json
import re
from pathlib import Path
from build_text_pages import split_text

ROOT = Path(__file__).resolve().parents[1]


def inventory():
    lib = json.loads((ROOT/'data/library.json').read_text())
    rows = []
    for work in lib['works']:
        for edition in work['editions']:
            if not edition.get('text'):
                continue
            raw = (ROOT/edition['text']).read_bytes()
            blocks = split_text(raw.decode('utf-8'))
            source = ROOT/('data/sources/'+edition['id']+'.json')
            assert source.is_file(), edition['id']
            assert hashlib.sha256(raw).hexdigest() == edition['sha256'], edition['id']
            rows.append(dict(work=work, edition=edition, blocks=len(blocks),
                             splitWords=len(re.findall(r'\w-\n[a-z]', '\n\n'.join(blocks))),
                             numerals=sum(bool(re.fullmatch(r'\d+', b)) for b in blocks),
                             emphasis=sum(bool(re.search(r'_[^_]+_', b)) for b in blocks)))
    return lib, rows


def cell(s):
    return str(s).replace('|', '\\|').replace('\n', ' ')


def main():
    lib, rows = inventory()
    hosted = {r['work']['id'] for r in rows}
    out = ['# Hosted reading editions', '',
           'Generated by `python3 tools/audit_hosted_texts.py` from the current catalogue and local bytes. '
           'Read [the editorial assessment](HOSTED-TEXT-QUALITY.md) for findings, priorities, and limits.', '',
           f"{len(lib['works'])} selected work records; {len(hosted)} works with {len(rows)} hosted editions; "
           f"{len(lib['works'])-len(hosted)} selected works without a hosted edition. "
           'Only an edition with `text` counts as hosted. External full-text access and samples do not count. '
           'This is a file inventory, not a completeness certification against printed editions.', '',
           'Indicators count the whole file, including front matter, contents, notes, and licenses. '
           '`H` = word-hyphen-newline-lowercase patterns; `N` = numeric-only blocks; '
           '`E` = blocks with paired underscore markers. These are candidates for inspection, not correction counts. '
           'A date or poem number is not a stray page number, and a hyphen may be intentional.', '',
           '| Work | Edition / source record | Hosted text | Blocks | H / N / E |',
           '|---|---|---|---:|---:|']
    for r in rows:
        w, e = r['work'], r['edition']
        out.append(f"| {cell(w['title'])} | [{e['id']}](../data/sources/{e['id']}.json) | "
                   f"[TXT](../{e['text']}) | {r['blocks']} | {r['splitWords']} / {r['numerals']} / {r['emphasis']} |")
    out += ['', '## Edition scope and existing bibliographic notes', '',
            'These are current catalogue statements, retained as evidence of the existing description. '
            'They have not all been independently reverified in this audit. Blank notes are a provenance gap; '
            'the linked source snapshot may still supply a title, contributor, and rights statement.', '']
    for r in rows:
        w, e = r['work'], r['edition']
        credits = '; '.join(c['role']+': '+c['name'] for c in e.get('contributors', []))
        out += [f"- **{w['title']} / {e['id']}**: {e.get('note') or 'No edition-specific catalogue note.'} "
                f"{credits or 'No contributor roles recorded.'} [Source]({e['source']}). "
                f"Source/rights check recorded: {e['checked']}. SHA-256: `{e['sha256']}`."]
    (ROOT/'docs/HOSTED-TEXT-INVENTORY.md').write_text('\n'.join(out)+'\n')
    print(f"Hosted inventory: {len(hosted)} works, {len(rows)} editions; all local hashes match.")


if __name__ == '__main__':
    main()
