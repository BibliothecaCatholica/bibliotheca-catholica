#!/usr/bin/env python3
"""Per-edition status table for docs/HOSTED-EDITIONS.md (owner instruction, November 15, 2026: "Add a per-edition
status table ... (automatic layout, structure file, chapter openers, cover, EPUB) and keep it current").

  python3 tools/edition_status.py           # rewrite the table between the markers
  python3 tools/edition_status.py --check   # exit 1 if the table is out of date (tests/test_published_epub.py)
"""
import json, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DOC = ROOT / 'docs/HOSTED-EDITIONS.md'
A, B = '<!-- edition-status:start -->', '<!-- edition-status:end -->'


def table():
    lib = json.loads((ROOT / 'data/library.json').read_text())
    tp = json.loads((ROOT / 'data/text-pages.json').read_text())['works']
    epubs = json.loads((ROOT / 'data/epubs.json').read_text())['epubs']
    covers = json.loads((ROOT / 'data/covers.json').read_text())['covers']
    report = json.loads((ROOT / 'data/auto-layout/report.json').read_text())
    structured = {}
    for p in sorted((ROOT / 'data/structured').glob('*.json')):
        d = json.loads(p.read_text())
        structured[d['edition']] = 'map' if d['gate'].get('mode') == 'map' else 'HTML'
    rows = ['| Edition | Work | Automatic layout | Structure file | Chapter openers | Cover | EPUB |', '|---|---|---|---|---|---|---|']
    yes = lambda b: 'yes' if b else '·'
    for w in sorted(lib['works'], key=lambda w: w['title'].lower()):
        for e in w['editions']:
            if not e.get('text'):
                continue
            al = 'excluded (verse)' if e['id'] in report['excluded'] else ('%d%%' % round(100 * report['editions'][e['id']]['share']) if e['id'] in report['editions'] else '·')
            t = tp.get(w['id'])
            openers = t and t['edition'] == e['id'] and 'partD' in t
            rows.append('| %s | %s | %s | %s | %s | %s | %s |' % (e['id'], w['title'], al, structured.get(e['id'], '·'), yes(openers),
                                                            yes(e['id'] in covers), yes(e['id'] in epubs)))
    n = len(rows) - 2
    summary = ('%d hosted editions: %d with a structure file, %d with chapter openers, %d with a cover, %d with a published EPUB. '
               'Automatic layout shows the share of multi-line blocks reflowed. Generated by `tools/edition_status.py`; do not edit by hand.'
               % (n, sum(1 for r in rows[2:] if r.split(' | ')[3] != '·'), sum(1 for r in rows[2:] if r.split(' | ')[4] == 'yes'),
                  sum(1 for r in rows[2:] if r.split(' | ')[5] == 'yes'), sum(1 for r in rows[2:] if r.split(' | ')[6].startswith('yes'))))
    return summary + '\n\n' + '\n'.join(rows)


def render(doc):
    a, b = doc.index(A) + len(A), doc.index(B)
    return doc[:a] + '\n' + table() + '\n' + doc[b:]


if __name__ == '__main__':
    doc = DOC.read_text()
    new = render(doc)
    if '--check' in sys.argv:
        sys.exit(0 if new == doc else 1)
    DOC.write_text(new)
    print('edition status table updated')
