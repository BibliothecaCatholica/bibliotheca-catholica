#!/usr/bin/env python3
"""Self-host the public-domain author portraits at list size (owner decision, November 14, 2026).

Run by hand, with network access to upload.wikimedia.org / thumb.wikimedia.org; never part of the build.
For every hub author whose portrait is cleared and public domain (imgCredit.pd, the same set list
thumbnails were already allowed to show), it downloads the existing `img` thumbnail once, crops it to a
square (centred, biased toward the top, where faces are), resizes it to SIZE px, and saves
assets/portraits/<id>.webp. It writes data/portraits.json: per author the file, its SHA-256, size,
the source URL it came from, and the credit fields copied from imgCredit (page, license, artist).
Person pages keep loading the larger image from Wikimedia with their credit line.

  python3 tools/fetch_portraits.py            download missing files, rewrite the manifest
  python3 tools/fetch_portraits.py --check    verify every file against the manifest (no network)
"""
import argparse, hashlib, io, json, sys, time, urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'assets/portraits'
MANIFEST = ROOT / 'data/portraits.json'
SIZE = 160          # rendered at 40 to 96 CSS px; 160 covers 2x screens at the common sizes
QUALITY = 78
UA = 'BibliothecaCatholicaPortraits/1.0 (one-time static build step)'


def eligible():
    hub = json.loads((ROOT / 'data/catholic-hub.json').read_text(encoding='utf-8'))
    for a in hub['authors']:
        c = a.get('imgCredit') or {}
        if a.get('img') and c.get('pd'):
            yield a


def square(im):
    w, h = im.size
    s = min(w, h)
    left = (w - s) // 2
    top = 0 if h <= w else min(h - s, int((h - s) * 0.15))
    return im.crop((left, top, left + s, top + s))


def thumb_url(url):
    """An unscaled original (upload.wikimedia.org/wikipedia/<wiki>/a/ab/File.jpg) becomes the same file's standard
    330 px thumbnail, which Wikimedia serves to scripts; thumbnail URLs are used as given."""
    import re
    m = re.match(r'(https://upload\.wikimedia\.org/wikipedia/[^/]+)/([0-9a-f])/([0-9a-f]{2})/([^?]+)', url)
    if not m or '/thumb/' in url:
        return url
    base, a, ab, name = m.groups()
    return '%s/thumb/%s/%s/%s/330px-%s' % (base, a, ab, name, name)


def fetch(url):
    for attempt in range(4):
        try:
            with urllib.request.urlopen(urllib.request.Request(url, headers={'User-Agent': UA}), timeout=40) as r:
                return r.read()
        except Exception as e:  # network hiccup or rate limit: back off, then give up
            if attempt == 3:
                raise
            time.sleep(2 ** attempt * 10)


def build():
    from PIL import Image
    OUT.mkdir(parents=True, exist_ok=True)
    old = json.loads(MANIFEST.read_text()) if MANIFEST.exists() else {'portraits': {}}
    rows, failed = {}, []
    for a in eligible():
        path = OUT / (a['id'] + '.webp')
        prev = old['portraits'].get(a['id'])
        if not (path.exists() and prev and prev.get('source') == a['img']):
            try:
                im = Image.open(io.BytesIO(fetch(thumb_url(a['img'])))).convert('RGB')
            except Exception as e:
                failed.append((a['id'], str(e)[:80]))
                continue
            square(im).resize((SIZE, SIZE), Image.LANCZOS).save(path, 'WEBP', quality=QUALITY, method=6)
            time.sleep(1.5)
        data = path.read_bytes()
        c = a['imgCredit']
        rows[a['id']] = {'file': 'assets/portraits/' + path.name, 'sha256': hashlib.sha256(data).hexdigest(), 'bytes': len(data),
                         'width': SIZE, 'height': SIZE, 'source': a['img'], 'fetched': thumb_url(a['img']), 'page': c.get('page', ''),
                         'license': c.get('license', ''), 'artist': c.get('artist', '')}
    keep = set(rows)
    for f in OUT.glob('*.webp'):
        if f.stem not in keep:
            f.unlink()
    MANIFEST.write_text(json.dumps({
        'note': 'Generated by tools/fetch_portraits.py. Public-domain portraits (imgCredit.pd) self-hosted at list size; '
                'person pages still load the larger image from Wikimedia with its credit. Do not edit by hand.',
        'size': SIZE, 'count': len(rows), 'portraits': dict(sorted(rows.items()))}, ensure_ascii=False, indent=1) + '\n')
    total = sum(r['bytes'] for r in rows.values())
    print('%d portraits, %.1f KB total' % (len(rows), total / 1024))
    for i, e in failed:
        print('FAILED', i, e)
    return 0 if not failed else 1


def check():
    m = json.loads(MANIFEST.read_text())
    bad = [i for i, r in m['portraits'].items()
           if not (ROOT / r['file']).exists() or hashlib.sha256((ROOT / r['file']).read_bytes()).hexdigest() != r['sha256']]
    print('%d portraits, %d bad' % (len(m['portraits']), len(bad)))
    return 1 if bad else 0


if __name__ == '__main__':
    ap = argparse.ArgumentParser()
    ap.add_argument('--check', action='store_true')
    sys.exit(check() if ap.parse_args().check else build())
