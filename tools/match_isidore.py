"""Match selected-library works to Isidore Index books (title + author, conservative).
Writes data/isidore-matches.json. Review the printout before committing; no network."""
import json,re,unicodedata
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
STOP={'the','a','an','of','on','saint','st','s','and','de','la','le','von','van','pope','blessed'}
def norm(s):
    s=unicodedata.normalize('NFKD',s or '').encode('ascii','ignore').decode().lower()
    s=re.sub(r"[’'`]", '', s);return re.sub(r'[^a-z0-9]+',' ',s).strip()
def core(t):
    t=' '.join('st' if x=='saint' else x for x in norm(t).split())
    t=re.sub(r'^(the|a|an) ','',t);t=re.sub(r'^holy ','',t);return t
NOT=re.compile(r'\b(commentary|companion|guide|study|studies|introduction|reader|notes|selections|abridged|excerpts|volume|vol)\b|, ?\d+$|\b[ivx]+$')
def main(verbose=True):
    lib=json.loads((ROOT/'data/library.json').read_text());bk=json.loads((ROOT/'data/books.json').read_text())
    A=bk['authors'];out={}
    for w in lib['works']:
        if w.get('tradition')=='Anglican':continue   # copyrighted Lewis titles: no download links
        wt=core(w['title']);atoks=[t for t in norm(w['author']).split() if t not in STOP and len(t)>=4]
        hits=[]
        for b in bk['books']:
            bid,title,auth,fmts=b[0],b[1],b[2],b[7]
            fs=[f for f in fmts.split('|') if f in('EPUB','PDF')]
            if not fs:continue
            an=norm(' '.join(A[i][0] for i in auth))
            if not atoks or not any(t in an.split() for t in atoks):continue
            cands={core(title),core(re.split(r'[:;(]',title)[0])}
            for c in list(cands):   # "The Confessions of Saint Augustine" -> "confessions" only if the tail names the author
                m=re.match(r'^(.*?) (of|by) (.+)$',c)
                if m and any(t in m.group(3).split() for t in atoks):cands.add(m.group(1))
            if NOT.search(norm(title)) or re.search(r', ?\d+\s*$',title):continue
            if wt not in cands and not (len(wt.split())>=3 and any(c.startswith(wt+' ') for c in cands)):continue
            hits.append({'id':bid,'t':title,'a':[A[i][0] for i in auth],'f':fs})
        if hits:out[w['id']]=hits
        if verbose:print(w['id'],'->',[(h['id'],h['t'][:50],h['a'][:2],h['f']) for h in hits])
    data={'server':bk['server'],'note':'Generated by tools/match_isidore.py: exact title (or author-named/long-prefix title) plus author-token match; EPUB/PDF only; partial volumes and commentaries excluded.','matches':out}
    (ROOT/'data/isidore-matches.json').write_text(json.dumps(data,ensure_ascii=False,indent=1)+'\n')
    (ROOT/'data/isidore-matches.js').write_text('window.ISIDORE_MATCHES='+json.dumps(data,ensure_ascii=False,separators=(',',':'))+';\n')
    return out
if __name__=='__main__':
    o=main();print(len(o),'works matched,',sum(len(v) for v in o.values()),'books')
