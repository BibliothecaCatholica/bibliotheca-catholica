#!/usr/bin/env python3
"""Related Church teaching (Job M1): Catechism paragraphs and magisterial documents linked to works, authors, saints,
and topics, each with an official Holy See URL and a short neutral label. Never a summary of doctrine.

Sources and method
  - The Catechism of the Catholic Church is read from its official English text on vatican.va
    (https://www.vatican.va/archive/ENG0015/_INDEX.HTM). `--index CACHE` parses a local copy of those pages into
    data/teaching/catechism-index.json: for every page, its URL, the paragraph numbers on it, and its heading path.
  - data/teaching/subjects.json (edited by hand) says what to look for: for a work or author, the citation forms the
    Catechism's own footnotes use ("St. Augustine, Conf."); for a saint, the name as the Catechism prints it; for a
    topic, a range of paragraphs and the heading that opens it; plus magisterial documents with their vatican.va URLs.
  - `--build CACHE` finds every Catechism paragraph whose text or footnotes contain a subject's citation form and
    writes data/teaching/entries.json. An entry is `verified` only when the citation form was found on the official
    page for that paragraph, and a document only when its URL answered 200 with the expected title on the page.
    Anything else is `unverified` and is never published.
  - The label is the Catechism's own heading for that paragraph, or the document's title and date.

  python3 tools/teaching/teaching.py --index CACHE         rebuild catechism-index.json from cached vatican.va pages
  python3 tools/teaching/teaching.py --build CACHE         rebuild entries.json (fetches only document URLs not yet checked)
  python3 tools/teaching/teaching.py --check               offline validation, also run by tests/test_teaching.py

Requests go only to www.vatican.va. Nothing is ever fetched from or stored about Magisterium AI's answers.
"""
import html, json, re, sys, time, urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DIR = ROOT / 'data' / 'teaching'
CCC_BASE = 'https://www.vatican.va/archive/ENG0015/'
CCC_MAX = 2865
OFFICIAL = re.compile(r'^https://www\.vatican\.va/')
UA = {'User-Agent': 'Mozilla/5.0 (Bibliotheca Catholica link check)'}
MAX_PARAGRAPHS = 8  # per subject: the panel stays short


def text_of(fragment):
    return html.unescape(re.sub(r'\s+', ' ', re.sub(r'<[^>]+>', ' ', fragment))).strip()


def parse_page(name, raw):
    """(heading path, {paragraph: text}, {footnote: text}, {paragraph: [footnote numbers]}) for one IntraText page."""
    path = []
    m = re.search(r'<ul type=square>(.*?)</ul></font>', raw, re.S | re.I)
    if m:
        path = [text_of(x) for x in re.findall(r'<li>(.*?)(?=<ul|</li>|$)', m.group(1), re.S | re.I)]
        path = [p for p in path if p]
    notes = {}
    for n, rest in re.findall(r'<a name=\$(\w+) href=#-\w+>\d+</a>(.*?)(?=<a name=\$\w+ href=#-|Previous</a>|$)', raw, re.S | re.I):
        notes[n] = text_of(rest)
    body = re.split(r'<hr size=1 width=30% align=left/?>', raw, flags=re.I)[0]
    paras, cites = {}, {}
    chunks = re.split(r'<p class=MsoNormal[^>]*>\s*(?:<(?:i|b|span)[^>]*>\s*)*(\d{1,4})\s', body, flags=re.I)
    for i in range(1, len(chunks) - 1, 2):
        n, chunk = int(chunks[i]), chunks[i + 1]
        if not 1 <= n <= CCC_MAX:
            continue
        chunk = re.split(r'<p class=MsoNormal[^>]*><b[ >]', chunk, flags=re.I)[0]  # stop at the next heading
        paras[n] = text_of(re.sub(r'<sup>.*?</sup>', ' ', chunk, flags=re.S | re.I))
        cites[n] = re.findall(r'<a name=-(\w+) href=#\$\w+>', chunk, flags=re.I)
    for n in sorted(paras):  # two paragraphs run on inside the one before (2077 in 2076, 2436 after a line break)
        m = re.search(r'(?:^|[.!?:"\u201d] )(%d) ([A-Z])' % (n + 1), paras[n])
        if m and n + 1 not in paras:
            paras[n], paras[n + 1] = paras[n][:m.start(1)].strip(), paras[n][m.start(1) + len(str(n + 1)):].strip()
            cites[n + 1] = []
    return path, paras, notes, cites


def load_cache(cache):
    pages = {}
    for p in sorted(Path(cache).glob('__P*.HTM')):
        pages[p.name] = parse_page(p.name, p.read_bytes().decode('latin-1'))
    return pages


def build_index(cache):
    out = []
    for name, (path, paras, notes, cites) in load_cache(cache).items():
        if paras:
            out.append({'url': CCC_BASE + name, 'paragraphs': sorted(paras), 'path': path})
    out.sort(key=lambda r: r['paragraphs'][0])
    seen = {}
    for r in out:
        for n in r['paragraphs']:
            assert n not in seen, (n, r['url'], seen[n])
            seen[n] = r['url']
    return {'source': CCC_BASE + '_INDEX.HTM', 'publisher': 'Libreria Editrice Vaticana; Internet Office of the Holy See',
            'note': 'Generated by tools/teaching.py --index from the official pages; each page URL with the paragraphs it holds.',
            'paragraphs': len(seen), 'pages': out}


SMALL = {'a', 'an', 'and', 'as', 'at', 'by', 'for', 'from', 'in', 'into', 'of', 'on', 'or', 'the', 'to', 'with'}


def title_case(t):
    words = t.lower().split(' ')
    out = []
    for i, w in enumerate(words):
        if i and w in SMALL:
            out.append(w)
        elif w in ('i', 'ii', 'iii', 'iv'):
            out.append(w.upper())
        else:
            out.append(re.sub(r'^([^\w]*)(\w)', lambda m: m.group(1) + m.group(2).upper(), w))
    return ' '.join(out)


def label_for(path):
    """The Catechism's own heading for a paragraph: the last line of its heading path, without its number, and in
    title case where the Catechism prints it in capitals. A heading, never a summary."""
    path = [p for p in path if p.strip().lower() != 'in brief'] or path  # an In Brief page takes its section's heading
    last = path[-1] if path else 'Catechism of the Catholic Church'
    last = re.sub(r'^(?:(?:Paragraph|Article|Chapter|Section|Part)\s+[\w]+\.?:?\s+)+', '', last, flags=re.I)
    last = re.sub(r'^(?:[IVXL]+|[0-9]+|[A-Z])\.\s+', '', last)
    letters = [c for c in last if c.isalpha()]
    if letters and sum(c.isupper() for c in letters) > 0.6 * len(letters):
        last = title_case(last)
    return last.strip(' -')[:90]


def fetch(url):
    with urllib.request.urlopen(urllib.request.Request(url, headers=UA), timeout=60) as r:
        return r.status, r.read().decode('utf-8', 'replace')


def build_entries(cache, today):
    subjects = json.loads((DIR / 'subjects.json').read_text(encoding='utf-8'))
    pages = load_cache(cache)
    where = {}
    for name, (path, paras, notes, cites) in pages.items():
        for n in paras:
            where[n] = name
    old = {}
    if (DIR / 'entries.json').exists():
        for e in json.loads((DIR / 'entries.json').read_text(encoding='utf-8'))['entries']:
            for d in e.get('documents', []):
                old[d['url']] = d
    entries = []
    for s in subjects['subjects']:
        hits = []
        if s.get('cites'):
            for n in sorted(where):
                path, paras, notes, cites = pages[where[n]]
                found = next((c for c in s['cites'] for f in cites.get(n, []) if c in notes.get(f, '')), None) \
                    or (next((c for c in s['cites'] if c in paras[n]), None) if s.get('inText') else None)
                if found:
                    hits.append({'ccc': n, 'url': CCC_BASE + where[n], 'label': label_for(path), 'check': found,
                                 'status': 'verified', 'checked': today})
        for a, b, heading in s.get('ranges', []):
            assert 1 <= a <= b <= CCC_MAX, (s['id'], a, b)
            path = pages[where[a]][0] if a in where else []
            ok = a in where and b in where and any(heading.lower() in p.lower() for p in path)
            hits.append({'ccc': [a, b], 'url': CCC_BASE + where.get(a, ''), 'label': label_for([heading]), 'check': heading,
                         'status': 'verified' if ok else 'unverified', 'checked': today})
        total = len(hits)
        if s.get('cites') and len(hits) > MAX_PARAGRAPHS:  # keep the first paragraph under each distinct heading
            by_label, keep = set(), []
            for h in hits:
                if h['label'] not in by_label:
                    by_label.add(h['label'])
                    keep.append(h)
            hits = keep[:MAX_PARAGRAPHS]
        docs = []
        for d in s.get('documents', []):
            prev = old.get(d['url'])
            if prev and prev.get('status') == 'verified' and prev.get('title') == d['title'] and prev.get('expect') == d['expect']:
                docs.append(dict(prev, label=d['label']))  # checked already: the URL answered with the expected title
                continue
            status = 'unverified'
            try:
                code, page = fetch(d['url'])
                if code == 200 and OFFICIAL.match(d['url']) and d['expect'].lower() in page.lower():
                    status = 'verified'
                time.sleep(0.5)
            except Exception:
                pass
            docs.append({'title': d['title'], 'url': d['url'], 'label': d['label'], 'expect': d['expect'],
                         'status': status, 'checked': today})
        entries.append({'kind': s['kind'], 'id': s['id'], 'name': s['name'], 'catechism': hits,
                        'catechismMatches': total, 'documents': docs})
    return {'note': ('Generated by tools/teaching.py --build. Labels are the Catechism\'s own headings or a document\'s '
                     'title and date, never a summary of doctrine. Only entries with status "verified" are published.'),
            'checked': today, 'entries': entries}


def known_ids():
    lib = json.loads((ROOT / 'data/library.json').read_text(encoding='utf-8'))
    saints = json.loads((ROOT / 'data/saints.json').read_text(encoding='utf-8'))['saints']
    authors = {p.name for p in (ROOT / 'author').iterdir() if p.is_dir()}
    flags = json.loads((ROOT / 'data/editorial-flags.json').read_text(encoding='utf-8'))
    return ({w['id']: w for w in lib['works']}, authors, {s['id'] for s in saints}, flags)


def fringe_work(w, flags):
    return bool(w.get('editorialFlag') or w.get('flag') or str(w.get('id')) in flags.get('books', {}))


def check(data=None):
    """Offline validation: returns a list of problems (empty when the data is sound)."""
    problems = []
    idx = json.loads((DIR / 'catechism-index.json').read_text(encoding='utf-8'))
    page_of = {n: r['url'] for r in idx['pages'] for n in r['paragraphs']}
    works, authors, saints, flags = known_ids()
    subjects = json.loads((DIR / 'subjects.json').read_text(encoding='utf-8'))
    topics = {s['id'] for s in subjects['subjects'] if s['kind'] == 'topic'}
    data = data or json.loads((DIR / 'entries.json').read_text(encoding='utf-8'))
    for e in data['entries']:
        k, i = e['kind'], e['id']
        if k == 'work' and i not in works:
            problems.append(f'work {i}: no such work in data/library.json')
        elif k == 'work' and fringe_work(works[i], flags):
            problems.append(f'work {i}: flagged works get no teaching panel')
        elif k == 'author' and i not in authors:
            problems.append(f'author {i}: no author page')
        elif k == 'saint' and i not in saints:
            problems.append(f'saint {i}: not in data/saints.json')
        elif k == 'topic' and i not in topics:
            problems.append(f'topic {i}: not in subjects.json')
        for c in e['catechism']:
            nums = c['ccc'] if isinstance(c['ccc'], list) else [c['ccc']]
            for j, n in enumerate(nums):
                if not (isinstance(n, int) and 1 <= n <= CCC_MAX):
                    problems.append(f'{k} {i}: Catechism {n} is out of range 1-{CCC_MAX}')
                elif j == 0 and page_of.get(n) != c['url']:  # a range links the page where it starts
                    problems.append(f'{k} {i}: Catechism {n} is not on {c["url"]}')
            if len(nums) == 2 and isinstance(nums[0], int) and isinstance(nums[1], int) and nums[0] > nums[1]:
                problems.append(f'{k} {i}: range {nums} runs backwards')
            if not OFFICIAL.match(c['url']):
                problems.append(f'{k} {i}: {c["url"]} is not an official Holy See URL')
            if not c.get('label') or len(c['label']) > 90:
                problems.append(f'{k} {i}: label missing or longer than 90 characters')
            if c['status'] not in ('verified', 'unverified'):
                problems.append(f'{k} {i}: bad status {c["status"]}')
        for d in e['documents']:
            if not OFFICIAL.match(d['url']):
                problems.append(f'{k} {i}: {d["url"]} is not an official Holy See URL')
            if not d.get('label') or len(d['label']) > 90:
                problems.append(f'{k} {i}: document label missing or longer than 90 characters')
    return problems


def published(kind, sid):
    """The verified Catechism references and documents for one subject, or None. Unverified entries never appear."""
    data = json.loads((DIR / 'entries.json').read_text(encoding='utf-8'))
    for e in data['entries']:
        if e['kind'] == kind and e['id'] == sid:
            cs = [c for c in e['catechism'] if c['status'] == 'verified']
            ds = [d for d in e['documents'] if d['status'] == 'verified']
            return (e, cs, ds) if cs or ds else None
    return None


def main(argv):
    if argv[:1] == ['--index']:
        (DIR / 'catechism-index.json').write_text(json.dumps(build_index(argv[1]), ensure_ascii=False, indent=1) + '\n', encoding='utf-8')
    elif argv[:1] == ['--build']:
        today = argv[2] if len(argv) > 2 else time.strftime('%Y-%m-%d')
        (DIR / 'entries.json').write_text(json.dumps(build_entries(argv[1], today), ensure_ascii=False, indent=1) + '\n', encoding='utf-8')
    elif argv[:1] == ['--check']:
        p = check()
        print('\n'.join(p) or 'data/teaching: ok')
        return 1 if p else 0
    else:
        print(__doc__)
        return 2
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
